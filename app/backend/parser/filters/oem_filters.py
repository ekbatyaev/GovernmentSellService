# Функция фильтрация

def request_filters_oem(work_name: str, debug: bool = False) -> Dict[str, Any]:
    """
    Возвращает словарь с решением и сработавшими группами.
    """
    text = _normalize(work_name)

    force_exclude = _matches(EXCLUDE_FORCE_PATTERNS_OEM, text)
    force_include = _matches(INCLUDE_FORCE_PATTERNS_OEM, text)
    has_object = _matches(OBJECT_PATTERNS_OEM, text)
    has_component = _matches(COMPONENT_PATTERNS_OEM, text)
    has_brand = _matches(BRAND_PATTERNS_OEM, text)
    has_electricity_indicators = _matches(FILTERS_WORK_PATTERNS_OEM, text)
    excluded_hard = _matches(EXCLUDE_HARD_PATTERNS_OEM, text)
    excluded_soft = _matches(EXCLUDE_SOFT_PATTERNS_OEM, text)

    reason = ""
    result = False

    if force_exclude:
        result = False
        reason = "force_exclude: спорный, но в таблице размечен как неподходящий"
    elif force_include:
        result = True
        reason = "force_include: спорный, но в таблице размечен как подходящий"
    elif excluded_hard:
        result = False
        reason = "hard_exclude: нерелевантный предмет закупки"
    elif has_object or has_component or has_brand:
        result = True
        reason = "direct_match: прямой маркер продукции/системы/бренда"
    elif has_electricity_indicators:
        result = True
        reason = "controlled_object: смежный объект управления"
    elif excluded_soft:
        result = False
        reason = "soft_exclude: общий тендер без релевантных маркеров"
    else:
        result = False
        reason = "no_match: нет релевантных маркеров"

    return {
        "result": result,
        "reason": reason,
        "force_exclude": force_exclude,
        "force_include": force_include,
        "object": has_object,
        "component": has_component,
        "brand": has_brand,
        "controlled_object": has_electricity_indicators,
        "exclude_hard": excluded_hard,
        "exclude_soft": excluded_soft,
    }

# Вспомогательные функции

def _normalize(text: str) -> str:
    text = str(text or "")
    text = text.replace("ё", "е").replace("Ё", "Е")
    text = re.sub(r"[\u00A0\t\r\n]+", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def _matches(patterns, text: str):
    return [p.pattern for p in patterns if p.search(text)]
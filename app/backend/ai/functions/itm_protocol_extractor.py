async def itm_get_model_extraction(message) -> Dict:

    user_content = \
        [
            {
                "type": "input_text",
                "text": f"Проанализируй следующий текст закупки и извлеки поля:\n\n{message}"
            }
        ]

    try:
        fields: Dict[str, Any] = await client.send_request(system_prompt=SYSTEM_PROMPT,
                                                           user_content=user_content, guided_json=GUIDED_JSON,
                                                           temperature=0.1)
        logger.info(fields)

    except Exception as e:
        logger.error(f"Ошибка при обработке запроса", e)
        raise
    return fields




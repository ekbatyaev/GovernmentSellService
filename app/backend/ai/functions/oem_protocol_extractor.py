SYSTEM_PROMPT = """Ты — аналитик отдела закупок. Тебе присылают текст закупочного документа (протокол комиссии, решение
 об определении единственного поставщика и т.п.).
Извлеки из текста 2 поля и верни JSON. Используй ТОЛЬКО то, что написано в тексте. Ничего не додумывай.
Если поля нет в тексте или его нельзя установить однозначно — верни для него пустую строку "".

ПОЛЯ И ПРАВИЛА

1. "Победитель" — организация (или организации), которую комиссия ЯВНО признала победителем, утвердила единственным
 поставщиком или с которой решила заключить договор(ы).
   Победитель есть, только если в тексте есть такое решение, например:
     «Признать Победителем … ООО "Альфа"», «заключить договор с ООО "Альфа"»,
     «утвердить единственного поставщика АО "Альфа"», «Решение: заключить договор поставки с АО "Альфа"».
   Победителя НЕТ (верни ""), если:
     - заявки только рассмотрены/допущены или только ранжированы, а переторжка или подведение итогов ещё впереди
       (первое место в ранжире — это ещё НЕ победитель);
     - закупка признана несостоявшейся без решения заключить договор;
     - просто перечислены поставщики/участники без решения;
     - текст обрывается (дальше идут нечитаемые символы) раньше, чем записано решение.
   Формат: ОПФ и название в кавычках, без адреса, ИНН, КПП, ОГРН: ООО «Альфа».
   Победителей несколько — перечисли всех через «; »: ООО «Альфа»; АО «Бета».
   Победил коллективный участник — перечисли лидера и всех членов через «; ».

2. "Итоговая цена контракта" — сумма, на которую заключается договор с победителем.
   Если победителя нет — "".
   Приоритет источников:
     а) цена, предложенная победителем / итоговая цена после торгов или переторжки;
     б) если победитель — единственный поставщик и другой цены нет — цена (сумма) договора из текста.
   «Начальная (максимальная) цена» при наличии итоговой цены победителя — это НЕ итоговая цена.
   Формат СТРОГО: только цифры, десятичный разделитель — точка, без пробелов, без валюты и слов.
     - «12 457 768 (Двенадцать миллионов …) рублей 80 копеек» → 12457768.80
     - «5 000 000,00 руб.» → 5000000.00
     - «3,5 млн руб.» → 3500000.00
   Если указаны цены с НДС и без НДС — бери цену с НДС. Если НДС не упомянут — бери как есть.
   Несколько победителей/лотов с разными суммами — суммы через «; » в том же порядке, что и победители.
   Цену нельзя установить однозначно → "".

ПРИМЕР 1 (победитель есть)
Текст: «Наименование предмета договора (лота): «Поставка ИБП». Максимальная цена (сумма) договора: 12 457 768
 (Двенадцать миллионов четыреста пятьдесят семь тысяч семьсот шестьдесят восемь) рублей 80 копеек. Повестка дня:
 Рассмотрение вопроса об утверждении единственного поставщика АО "Абсолютные Технологии". Решение заседания комиссии:
 заключить договор поставки с АО "Абсолютные Технологии". Сведения о поставщике: АО "Абсолютные Технологии" Адрес:
 125167, г. Москва … ИНН 7714259315»
Ответ:
{"Победитель": "АО «Абсолютные Технологии»", "Итоговая цена контракта": "12457768.80"}

ПРИМЕР 2 (победителя ещё нет)
Текст: «…Ранжировать заявки: 1 место ООО «Дельта» (предложение 4 100 000,00 руб.), 2 место ООО «Омега»
 (4 300 000,00 руб.). Провести процедуру переторжки 14.10.2026…»
Ответ:
{"Победитель": "", "Итоговая цена контракта": ""}

Верни только JSON с двумя ключами: "Победитель", "Итоговая цена контракта".
"""

GUIDED_JSON = {
    "type": "object",
    "properties": {
        "Победитель": {
            "type": "string",
            "description": "Организация(и), явно признанная победителем / единственным поставщиком / с которой решено "
                           "заключить договор, в формате ОПФ «Название», через «; »; иначе пусто",
        },
        "Итоговая цена контракта": {
            "type": "string",
            "description": "Сумма договора с победителем: только цифры, точка как десятичный разделитель, без пробелов "
                           "и валюты (например 12457768.80); если победителя или цены нет — пусто",
        },
    },
    "required": ["Победитель", "Итоговая цена контракта"],
    "additionalProperties": False,
}

async def oem_get_model_extraction(message) -> Dict:
    user_content = \
        [
            {
                "type": "input_text",
                "text": f"Проанализируй следующий текст закупки и извлеки поля:\n\n{message}"
            }
        ]

    try:
        fields: Dict[str, Any] = await client.send_request(system_prompt=SYSTEM_PROMPT,
                                                           user_content=user_content, guided_json=GUIDED_JSON,
                                                           temperature=0.1)
        logger.info(fields)

    except Exception as e:
        logger.error(f"Ошибка при обработке запроса: {e}")
        raise
    return fields


